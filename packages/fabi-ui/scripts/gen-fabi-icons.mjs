// Generates src/fabi-icons.ts (@fabi/ui/fabi-icons) and icons/catalog.json from icons/line/*.svg,
// icons/solid/*.svg and icons/manifest.json (written by fetch-fabi-icons.mjs). Run after every fetch,
// then `npm run build`.
//
// Names (user 2026-10-13): "home-03-line" → Home03Line, "home-03" (solid) → Home03Solid.
// Markup: the design's SVG export, unchanged except black → currentColor (outside masks, where black
// means "hidden"), so an icon takes the text colour like antd's icons.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const icons = join(root, 'icons')
const manifest = JSON.parse(readFileSync(join(icons, 'manifest.json'), 'utf8'))

const pascal = (s) => s.split(/[^a-zA-Z0-9]+/).filter(Boolean).map((w) => w[0].toUpperCase() + w.slice(1)).join('')
const BLACK = /\b(fill|stroke)="(?:black|#000|#000000)"/g
const problems = []

function markup(item) {
  const svg = readFileSync(join(icons, item.file), 'utf8').trim()
  const m = /^<svg\b([^>]*)>([\s\S]*)<\/svg>$/.exec(svg)
  if (!m) throw new Error(`${item.file}: not an <svg> document`)
  if (!/viewBox="0 0 24 24"/.test(m[1])) problems.push(`${item.file}: viewBox is not 0 0 24 24 (${m[1].trim()})`)
  // keep masks as they are: inside <mask>, black / white are visibility, not colour
  const parts = m[2].split(/(<mask\b[\s\S]*?<\/mask>)/)
  const body = parts.map((p) => (p.startsWith('<mask') ? p : p.replace(BLACK, '$1="currentColor"'))).join('').replace(/\s*\n\s*/g, '')
  const other = [...body.replace(/<mask\b[\s\S]*?<\/mask>/g, '').matchAll(/\b(?:fill|stroke)="(?!none|currentColor|url\()([^"]+)"/g)].map((x) => x[1])
  if (other.length) problems.push(`${item.file}: other colours kept: ${[...new Set(other)].join(', ')}`)
  return body
}

const used = new Map()
const entries = manifest.map((item) => {
  const base = item.style === 'line' ? item.name.replace(/-line$/, '') : item.name
  const dup = /~(\d+)\.svg$/.exec(item.file)
  let name = `${pascal(base)}${dup ? dup[1] : ''}${item.style === 'line' ? 'Line' : 'Solid'}`
  if (/^[0-9]/.test(name)) name = `Icon${name}`
  if (used.has(name)) throw new Error(`two icons named ${name}: ${used.get(name)} and ${item.file}`)
  used.set(name, item.file)
  return { ...item, base: dup ? `${base}~${dup[1]}` : base, component: name, markup: markup(item) }
})

const lines = [
  '// GENERATED by scripts/gen-fabi-icons.mjs from icons/ (the design\'s icon set). Do not edit by hand.',
  `// ${entries.filter((e) => e.style === 'line').length} line + ${entries.filter((e) => e.style === 'solid').length} solid icons, 24 × 24.`,
  "import { createFabiIcon as icon } from './fabiIcon.js'",
  '',
  "export { createFabiIcon } from './fabiIcon.js'",
  "export type { FabiIcon, FabiIconProps, FabiIconStyle } from './fabiIcon.js'",
  '',
  ...entries
    .sort((a, b) => a.component.localeCompare(b.component))
    .map((e) => `/** ${e.name} (${e.style}, ${e.category})${e.keywords ? `: ${e.keywords.replace(/\*\//g, '')}` : ''} */\nexport const ${e.component} = /*#__PURE__*/ icon(${JSON.stringify(e.component)}, ${JSON.stringify(e.name)}, ${JSON.stringify(e.style)}, ${JSON.stringify(e.markup)})`),
  '',
]
writeFileSync(join(root, 'src', 'fabi-icons.ts'), lines.join('\n'))

// catalog for the Storybook gallery: one row per icon name, with its line and solid components
const rows = new Map()
for (const e of entries) {
  const row = rows.get(e.base) ?? { name: e.base, category: e.category, keywords: e.keywords, line: null, solid: null }
  row[e.style] = e.component
  if (!row.keywords && e.keywords) row.keywords = e.keywords
  rows.set(e.base, row)
}
const catalog = [...rows.values()].sort((a, b) => a.category.localeCompare(b.category) || a.name.localeCompare(b.name))
writeFileSync(join(icons, 'catalog.json'), `${JSON.stringify(catalog, null, 1)}\n`)

const both = catalog.filter((r) => r.line && r.solid).length
console.log(`${entries.length} components → src/fabi-icons.ts; ${catalog.length} names (${both} with line + solid) → icons/catalog.json`)
console.log(`only line: ${catalog.filter((r) => !r.solid).map((r) => r.name).join(', ') || '—'}`)
console.log(`only solid: ${catalog.filter((r) => !r.line).map((r) => r.name).join(', ') || '—'}`)
if (problems.length) console.log(`check:\n  ${problems.join('\n  ')}`)
